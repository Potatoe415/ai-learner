// Stage 4 · Build: content/03-lessons/ (Markdown) -> lib/generated/content.ts (typed data for the site).
// Stateless: reads only stage 3, rewrites its whole output, same input gives the same output.
// Every content error is reported with file:line; the site is not built until they are fixed.
// Usage: npm run content:build (also runs before dev, build and typecheck).

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { ContentError, parseDoc } from "./lib/markdown.mjs";
import { readConceptQuiz, readDeliverable, readLab, readModule, readCaseStudy, readReading, readTrail, readZone } from "./lib/read-site.mjs";
import { STAGES, abs, readText } from "./lib/files.mjs";

/** Unit file name -> key in LessonContent, its reader, and the unit kind it fills. */
const UNIT_FILES = {
  "history.md": { key: "history", read: readReading, unit: "History" },
  "concept.md": { key: "reading", read: readReading, unit: "Concept" },
  "concept-quiz.md": { key: "concept", read: readConceptQuiz, unit: "Concept" },
  "case-study.md": { key: "caseStudy", read: readCaseStudy, unit: "Case study" },
  "lab.md": { key: "lab", read: readLab, unit: "Lab" },
  "deliverable.md": { key: "deliverable", read: readDeliverable, unit: "Deliverable" },
};

const errors = [];

/** Runs `fn` and records a content error instead of stopping, so one run reports every broken file. */
function attempt(fn) {
  try {
    return fn();
  } catch (e) {
    if (!(e instanceof ContentError)) throw e;
    errors.push(e.message);
    return undefined;
  }
}

const read = (relPath, reader) => attempt(() => reader(parseDoc(readText(relPath), relPath)));
const dirs = (relDir) => readdirSync(abs(relDir), { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
const files = (relDir) => readdirSync(abs(relDir), { withFileTypes: true }).filter((d) => d.isFile()).map((d) => d.name).sort();

function buildTrail(dir) {
  const trailDoc = read(`${dir}/trail.md`, readTrail);
  if (!trailDoc) return null;

  const zones = [];
  const zoneFiles = existsSync(abs(`${dir}/zones`)) ? files(`${dir}/zones`) : [];
  for (const key of trailDoc.zoneKeys) {
    const file = `${dir}/zones/${key}.md`;
    if (!zoneFiles.includes(`${key}.md`)) { errors.push(`${dir}/trail.md: zone "${key}" has no file ${file}`); continue; }
    const zone = read(file, readZone);
    if (zone && zone.key !== key) errors.push(`${file}: key "${zone.key}" must match the file name "${key}"`);
    if (zone) zones.push(zone);
  }
  for (const f of zoneFiles) if (!trailDoc.zoneKeys.includes(f.replace(/\.md$/, ""))) errors.push(`${dir}/zones/${f}: zone not listed in trail.md "zones"`);

  const modules = [];
  const lessons = {};
  for (const name of dirs(dir).filter((d) => d !== "zones")) {
    const mdir = `${dir}/${name}`;
    const match = /^module-(\d+)$/.exec(name);
    if (!match) { errors.push(`${mdir}: folders are "zones" or "module-<n>"`); continue; }
    const mod = read(`${mdir}/module.md`, readModule);
    if (!mod) continue;
    if (mod.n !== Number(match[1])) errors.push(`${mdir}/module.md: n is ${mod.n} but the folder is ${name}`);
    if (!trailDoc.zoneKeys.includes(mod.zone)) errors.push(`${mdir}/module.md: unknown zone "${mod.zone}"`);
    modules.push(mod);

    const content = {};
    const present = files(mdir).filter((f) => f !== "module.md");
    for (const f of present) {
      const spec = UNIT_FILES[f];
      if (!spec) { errors.push(`${mdir}/${f}: unknown file (allowed: module.md, ${Object.keys(UNIT_FILES).join(", ")})`); continue; }
      if (!mod.units.includes(spec.unit)) { errors.push(`${mdir}/${f}: the module has no ${spec.unit} unit (see "units" in module.md)`); continue; }
      const data = read(`${mdir}/${f}`, spec.read);
      if (data) content[spec.key] = data;
    }
    for (const unit of mod.units) {
      const expected = Object.entries(UNIT_FILES).filter(([, s]) => s.unit === unit).map(([f]) => f);
      if (!expected.some((f) => present.includes(f))) errors.push(`${mdir}: unit ${unit} needs ${expected.join(" or ")}`);
    }
    lessons[mod.n] = content;
  }

  modules.sort((a, b) => a.n - b.n);
  if (modules.length === 0) errors.push(`${dir}: no module-<n> folder`);
  modules.forEach((m, i) => { if (m.n !== i + 1) errors.push(`${dir}: modules must be numbered 1 to ${modules.length} without gaps`); });
  for (const d of trailDoc.deliverables) if (!modules.some((m) => m.n === d.module)) errors.push(`${dir}/trail.md: deliverable "${d.title}" points to a missing module ${d.module}`);

  return { trail: trailDoc.trail, zones, modules, deliverables: trailDoc.deliverables, lessons };
}

function render({ trail, zones, modules, deliverables, lessons }) {
  const json = (v) => JSON.stringify(v, null, 2);
  return `// GENERATED by scripts/content/build.mjs from ${STAGES.site}/. Do not edit: change the Markdown and rebuild.
import type { CourseModule, Deliverable, Zone } from "../curriculum";
import type { LessonContent } from "../lessons";

export const TRAIL = ${json(trail)};

export const ZONES: Zone[] = ${json(zones)};

export const MODULES: CourseModule[] = ${json(modules)};

export const DELIVERABLES: Deliverable[] = ${json(deliverables)};

export const LESSONS: Record<number, LessonContent> = ${json(lessons)};
`;
}

const trails = existsSync(abs(STAGES.site)) ? dirs(STAGES.site) : [];
if (trails.length !== 1) {
  errors.push(`${STAGES.site}: expected exactly one trail folder, found ${trails.length}. The site shows one trail for now.`);
}
const result = trails.length === 1 ? buildTrail(`${STAGES.site}/${trails[0]}`) : null;

if (errors.length || !result) {
  console.error(`content:build failed with ${errors.length} error(s):\n${errors.map((e) => `  - ${e}`).join("\n")}`);
  process.exit(1);
}

const out = `${STAGES.generated}/content.ts`;
const text = render(result);
mkdirSync(abs(STAGES.generated), { recursive: true });
const before = existsSync(abs(out)) ? readFileSync(abs(out), "utf8") : null;
if (before !== text) writeFileSync(abs(out), text);
const units = Object.values(result.lessons).reduce((n, c) => n + Object.keys(c).length, 0);
console.log(`content:build ok · ${result.modules.length} modules, ${units} unit files, ${result.zones.length} zones -> ${out}${before === text ? " (unchanged)" : ""}`);
